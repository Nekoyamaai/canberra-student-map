-- Canberra Student Favourite Places
-- Run this whole file in Supabase SQL Editor.

create table if not exists public.student_places (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 100),
  category text not null check (category in ('Cafe','Food','Nature','Study','Shopping','Entertainment','Other')),
  reason text not null default '' check (char_length(reason) <= 300),
  student_name text check (student_name is null or char_length(student_name) <= 60),
  lat double precision not null check (lat between -35.6 and -34.9),
  lng double precision not null check (lng between 148.6 and 149.6),
  created_at timestamptz not null default now()
);

alter table public.student_places enable row level security;

-- Anyone with the public site can read places.
drop policy if exists "Anyone can read student places" on public.student_places;
create policy "Anyone can read student places"
on public.student_places
for select
to anon, authenticated
using (true);

-- Anyone can submit a place from the public site.
-- No update/delete is exposed to anonymous users.
drop policy if exists "Anyone can submit student places" on public.student_places;
create policy "Anyone can submit student places"
on public.student_places
for insert
to anon, authenticated
with check (true);

-- Realtime publication. If this is already enabled in your project,
-- the final statement may say the table is already a member.
alter publication supabase_realtime add table public.student_places;

